/**
 * XLT Modern Load Report — Interactive ECharts 6 Dynamic Overview Loader
 *
 * @fileoverview
 * Powers the `"Dynamic Overview"` chart tab inside `workbench.js` (top Workbench and Stream cards).
 * Fetches per-entity time-series JSON files (`charts/<type>/<chartBase>.json`) and renders an interactive
 * ECharts 6 canvas with Mean runtime, Min–Max confidence band, Count/s throughput, and box-zoom/slider-zoom.
 *
 * Data Tuple Contract:
 * Each JSON file is an array of 5-element numeric tuples generated by XLT:
 *   `[timestampMs, meanMs, minMs, maxMs, countPerSec]`
 *
 * Constraints:
 * - Browsers block `fetch()` of sibling `.json` files when viewing a report over `file://` due to
 *   opaque-origin CORS; falls back to `XMLHttpRequest` over `file://` and renders an inline HTTP-server
 *   hint if blocked by browser security policy.
 * - Exposes `window.XltDynamicChart = { render: renderDynamicChart, dispose: disposeDynamicChart }`.
 */
(function () {
  "use strict";

  /** Maps DOM stage containers to their initialized ECharts instance (auto-GC'd on node removal). */
  var instances = new WeakMap();
  /** Maps DOM stage containers to their ResizeObserver so resizing never leaks window listeners. */
  var observers = new WeakMap();
  /** In-memory JSON response cache keyed by URL so switching tabs/items avoids duplicate fetches. */
  var cache = Object.create(null);

  /**
   * Disposes an ECharts instance and its ResizeObserver for `container`, if initialized.
   * @param {HTMLElement} container Stage element.
   */
  function disposeDynamicChart(container) {
    if (!container) return;
    var ro = observers.get(container);
    if (ro) {
      ro.disconnect();
      observers.delete(container);
    }
    var chart = instances.get(container);
    if (chart) {
      if (typeof chart.isDisposed !== "function" || !chart.isDisposed()) {
        chart.dispose();
      }
      instances.delete(container);
    }
  }

  /**
   * Fetches and caches a chart JSON series array from `url`, with `file://` XHR fallback.
   * @param {string} url Relative path to `charts/<type>/<chartBase>.json`.
   * @returns {Promise<Array<Array<number>>>} Resolved array of time-series tuples.
   */
  function fetchSeries(url) {
    if (cache[url]) return Promise.resolve(cache[url]);
    return fetch(url).then(function (res) {
      if (!res.ok) throw new Error("HTTP " + res.status + " loading " + url);
      return res.json();
    }).catch(function (fetchErr) {
      if (window.location && window.location.protocol === "file:" && typeof XMLHttpRequest !== "undefined") {
        return new Promise(function (resolve, reject) {
          var xhr = new XMLHttpRequest();
          xhr.open("GET", url, true);
          if (xhr.overrideMimeType) xhr.overrideMimeType("application/json");
          xhr.onload = function () {
            if ((xhr.status === 200 || xhr.status === 0) && xhr.responseText) {
              try {
                resolve(JSON.parse(xhr.responseText));
              } catch (parseErr) {
                reject(parseErr);
              }
            } else {
              reject(new Error("Status " + xhr.status + " loading " + url));
            }
          };
          xhr.onerror = function () { reject(fetchErr); };
          try {
            xhr.send();
          } catch (_) {
            reject(fetchErr);
          }
        });
      }
      throw fetchErr;
    }).then(function (data) {
      cache[url] = data;
      return data;
    });
  }

  /**
   * Initializes or reuses an ECharts instance in `container` and renders `jsonUrl`.
   *
   * @param {HTMLElement} container Stage element (e.g. `#wb-echart-canvas` or `.stream-echart-box`).
   * @param {string} jsonUrl Relative URL of the chart JSON file.
   * @param {string} title Chart heading shown above the canvas (entity/timer name).
   */
  function renderDynamicChart(container, jsonUrl, title) {
    if (!window.echarts || !container) return;
    var chart = instances.get(container);
    if (!chart) {
      chart = window.echarts.init(container);
      instances.set(container, chart);
      chart.on("restore", function () {
        chart.dispatchAction({
          type: "takeGlobalCursor",
          key: "dataZoomSelect",
          dataZoomSelectActive: true
        });
      });
      if (typeof ResizeObserver !== "undefined") {
        var ro = new ResizeObserver(function () {
          if (instances.get(container) === chart && (typeof chart.isDisposed !== "function" || !chart.isDisposed())) {
            chart.setOption({
              title: {
                textStyle: {
                  width: Math.max(220, (container.clientWidth || 860) - 96)
                }
              }
            });
            chart.resize();
          }
        });
        ro.observe(container);
        observers.set(container, ro);
      }
    }
    chart.showLoading({ text: "Loading interactive time series…", color: "#244b73" });

    var rgCfg = (window.XLT_META && window.XLT_META.reportGeneratorConfig) || {};
    var tzLabel = rgCfg.timeZoneLabel || "UTC";
    var tzOffset = Number(rgCfg.timeZoneOffset) || 0;

    fetchSeries(jsonUrl).then(function (rows) {
      if (instances.get(container) !== chart || (typeof chart.isDisposed === "function" && chart.isDisposed())) {
        return;
      }
      chart.hideLoading();
      var meanSeries = [];
      var minSeries = [];
      var diffSeries = [];
      var maxLookup = Object.create(null);
      var rateSeries = [];

      // Transform tuples into ECharts series; Min..Max band uses stacked [MinBase + (max - min)]
      for (var i = 0; i < rows.length; i++) {
        var r = rows[i];
        var ts = r[0] + tzOffset;
        var mean = r[1];
        var min = r[2];
        var max = r[3];
        var rate = r[4];
        meanSeries.push([ts, mean]);
        minSeries.push([ts, min]);
        diffSeries.push([ts, Math.max(0, max - min)]);
        maxLookup[ts] = max;
        rateSeries.push([ts, rate]);
      }

      chart.setOption({
        animation: false,
        backgroundColor: "#ffffff",
        useUTC: true,
        title: {
          text: title,
          left: "center",
          top: 6,
          textStyle: {
            fontSize: 12.5,
            fontWeight: 700,
            color: "#18181b",
            width: Math.max(220, (container.clientWidth || 860) - 96),
            overflow: "truncate",
            ellipsis: "…"
          }
        },
        legend: {
          bottom: 2,
          left: "center",
          itemGap: 18,
          data: ["Mean [ms]", "Min–Max Band", "Count/s"],
          textStyle: { fontSize: 11, color: "#3f3f46" }
        },
        toolbox: {
          show: true,
          top: 2,
          right: 10,
          feature: {
            dataZoom: {
              yAxisIndex: "none",
              filterMode: "none",
              icon: { zoom: "path://", back: "path://" }
            },
            restore: { title: "Reset Zoom" }
          }
        },
        tooltip: {
          trigger: "axis",
          axisPointer: { type: "cross", animation: false },
          backgroundColor: "rgba(255,255,255,0.96)",
          borderColor: "#d4d4d8",
          textStyle: { color: "#18181b", fontSize: 11.5 },
          formatter: function (params) {
            if (!params || !params.length) return "";
            var ts = params[0].value[0];
            var d = new Date(ts);
            var hh = String(d.getUTCHours()).padStart(2, "0");
            var mm = String(d.getUTCMinutes()).padStart(2, "0");
            var ss = String(d.getUTCSeconds()).padStart(2, "0");
            var meanV = "-", minV = "-", rateV = "-";
            params.forEach(function (p) {
              if (p.seriesName === "Mean [ms]") meanV = Number(p.value[1]).toLocaleString();
              if (p.seriesName === "MinBase") minV = Number(p.value[1]).toLocaleString();
              if (p.seriesName === "Count/s") rateV = Number(p.value[1]).toLocaleString();
            });
            var maxV = maxLookup[ts] !== undefined ? Number(maxLookup[ts]).toLocaleString() : "-";
            return (
              "<strong>" + hh + ":" + mm + ":" + ss + " " + tzLabel + "</strong><br/>" +
              "Mean: <strong>" + meanV + " ms</strong><br/>" +
              "Range: <strong>" + minV + " – " + maxV + " ms</strong><br/>" +
              "Throughput: <strong>" + rateV + " /s</strong>"
            );
          }
        },
        grid: { left: 66, right: 60, top: 34, bottom: 82 },
        dataZoom: [
          { type: "inside", xAxisIndex: 0 },
          { type: "slider", xAxisIndex: 0, height: 16, bottom: 28, showDetail: false }
        ],
        xAxis: {
          type: "time",
          name: "Time [" + tzLabel + "]",
          nameLocation: "middle",
          nameGap: 22,
          nameTextStyle: { fontSize: 10.5, color: "#3f3f46" },
          axisLine: { lineStyle: { color: "#a1a1aa" } },
          axisTick: { lineStyle: { color: "#a1a1aa" } },
          axisLabel: { fontSize: 10.5, color: "#3f3f46" },
          splitLine: { show: true, lineStyle: { color: "#e4e4e7", type: "dashed" } }
        },
        yAxis: [
          {
            type: "value",
            name: "Runtime [ms]",
            nameLocation: "middle",
            nameGap: 48,
            nameTextStyle: { fontSize: 11, fontWeight: 600, color: "#18181b" },
            axisLine: { show: true, lineStyle: { color: "#a1a1aa" } },
            axisTick: { show: true, lineStyle: { color: "#a1a1aa" } },
            axisLabel: { fontSize: 10.5, color: "#3f3f46" },
            splitLine: { lineStyle: { color: "#d4d4d8", type: "dashed" } }
          },
          {
            type: "value",
            name: "Count/s",
            nameLocation: "middle",
            nameRotate: 270,
            nameGap: 44,
            nameTextStyle: { fontSize: 11, fontWeight: 600, color: "#e07000" },
            axisLabel: { fontSize: 10.5, color: "#e07000" },
            splitLine: { show: false }
          }
        ],
        series: [
          {
            name: "MinBase",
            type: "line",
            data: minSeries,
            stack: "band",
            symbol: "none",
            lineStyle: { opacity: 0 }
          },
          {
            name: "Min–Max Band",
            type: "line",
            data: diffSeries,
            stack: "band",
            symbol: "none",
            lineStyle: { opacity: 0 },
            itemStyle: { color: "rgba(36, 75, 115, 0.28)" },
            areaStyle: { color: "rgba(36, 75, 115, 0.14)" },
            tooltip: { show: false }
          },
          {
            name: "Mean [ms]",
            type: "line",
            data: meanSeries,
            showSymbol: false,
            lineStyle: { width: 1.6, color: "#244b73" },
            itemStyle: { color: "#244b73" }
          },
          {
            name: "Count/s",
            type: "line",
            yAxisIndex: 1,
            data: rateSeries,
            showSymbol: false,
            lineStyle: { width: 1.2, color: "#e07000", type: "dashed" },
            itemStyle: { color: "#e07000" }
          }
        ]
      }, true);

      // Enable drag-to-zoom immediately without requiring a toolbar click first
      chart.dispatchAction({
        type: "takeGlobalCursor",
        key: "dataZoomSelect",
        dataZoomSelectActive: true
      });
    }).catch(function (err) {
      if (instances.get(container) !== chart || (typeof chart.isDisposed === "function" && chart.isDisposed())) {
        return;
      }
      disposeDynamicChart(container);
      container.innerHTML =
        '<div style="padding:28px;text-align:center;color:#71717a;font-size:12px;">' +
          'Interactive Dynamic Overview requires serving the report via HTTP (e.g. <code>http://localhost:8080/</code>) so browser CORS permits loading <code>' +
          jsonUrl + '</code>.<br/><span style="font-size:11px;opacity:0.8;">(' + String(err.message || err) + ')</span>' +
        '</div>';
    });
  }

  window.XltDynamicChart = { render: renderDynamicChart, dispose: disposeDynamicChart };
})();
