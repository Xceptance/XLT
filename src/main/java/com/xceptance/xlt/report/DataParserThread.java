package com.xceptance.xlt.report;

import java.util.List;
import java.util.Map.Entry;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.apache.commons.logging.Log;
import org.apache.commons.logging.LogFactory;

import com.xceptance.common.io.fs.FsResource;

import com.xceptance.common.util.CsvByteColumns;
import com.xceptance.common.util.CsvByteLineDecoder;
import com.xceptance.xlt.api.engine.ActionData;
import com.xceptance.xlt.api.engine.Data;
import com.xceptance.xlt.api.engine.PageLoadTimingData;
import com.xceptance.xlt.api.engine.RequestData;
import com.xceptance.xlt.api.report.PostProcessedDataContainer;
import com.xceptance.xlt.report.mergerules.MergeRule;
import com.xceptance.xlt.report.mergerules.MergeRuleProcessor;

/**
 * Parses lines to data records and performs any data record preprocessing that can 
 * be done in parallel. Preprocessing also includes executing request merge rules.
 */
class DataParserThread implements Runnable
{
    /**
     * Class logger.
     */
    private static final Log LOG = LogFactory.getLog(DataParserThread.class);

    /**
     * Pattern used to rename the name of Web driver timers generated by FF add-on.
     */
    private static final Pattern WD_TIMER_NAME_PATTERN = Pattern.compile("page_\\d+");

    /**
     * The data record factory.
     */
    private final DataRecordFactory dataRecordFactory;

    /**
     * The dispatcher that coordinates result processing.
     */
    private final Dispatcher dispatcher;

    /**
     * The start time of the report period. Data records generated outside this window will be ignored.
     */
    private final long fromTime;

    /**
     * The end time of the report period. Data records generated outside this window will be ignored.
     */
    private final long toTime;

    /**
     * The general config of the report generator
     */
    private final ReportGeneratorConfiguration config;

    /**
     * Constructor.
     *
     * @param dispatcher
     *            the dispatcher that coordinates result processing
     * @param dataRecordFactory
     *            the data record factory
     * @param fromTime
     *            the start time
     * @param toTime
     *            the end time
     * @param config
     *            the report generator settings
     */
    public DataParserThread(final Dispatcher dispatcher, final DataRecordFactory dataRecordFactory, 
                            final long fromTime, final long toTime,
                            final ReportGeneratorConfiguration config)
    {
        this.dataRecordFactory = dataRecordFactory;
        this.fromTime = fromTime;
        this.toTime = toTime;
        this.dispatcher = dispatcher;
        this.config = config;
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public void run()
    {
        // reusable CSV byte columns structure
        final CsvByteColumns csvColumns = new CsvByteColumns(50);

        // Build this thread's own independent set of merge rules on the parser thread itself.
        // Each parser thread compiles its own regex instances and maintains its own Condition
        // match result caches, ensuring a strict shared-nothing approach.
        final List<MergeRule> mergeRules = config.getMergeRules();

        // our request processing, this is move away from here to test it better
        final MergeRuleProcessor requestProcessing = new MergeRuleProcessor(mergeRules,
                                                                          config.getRemoveIndexesFromRequestNames());

        final PostProcessedDataContainer postProcessedData = new PostProcessedDataContainer(dispatcher.chunkSize);
        PostProcessedDataContainer nonRequestData = null;

        final boolean poolRequests = dataRecordFactory.isStandardRequestData();
        final boolean poolActions = dataRecordFactory.isStandardActionData();
        final boolean poolTransactions = dataRecordFactory.isStandardTransactionData();
        final boolean poolCustom = dataRecordFactory.isStandardCustomData();

        while (true)
        {
            try
            {
                // get a chunk of lines
                final DataChunk chunk = dispatcher.retrieveReadData();

                boolean finishedNotified = false;
                try
                {
                    final List<byte[]> lines = chunk.getLines();

                    final String agentName = chunk.getAgentName();
                    final String testCaseName = chunk.getTestCaseName();
                    final String userNumber = chunk.getUserNumber();
                    final boolean collectActionNames = chunk.getCollectActionNames();
                    final boolean adjustTimerName = chunk.getAdjustTimerNames();
                    final FsResource file = chunk.getFile();

                    final long _fromTime = fromTime;
                    final long _toTime = toTime;

                    // reset reusable containers for this chunk
                    postProcessedData.reset();
                    if (nonRequestData != null)
                    {
                        nonRequestData.reset();
                    }
                    int actionPoolIdx = 0;
                    int txnPoolIdx = 0;
                    int customPoolIdx = 0;

                    final int baseLineNumber = chunk.getBaseLineNumber();
                    final int size = lines.size();

                    try
                    {
                        for (int i = 0; i < size; i++)
                        {
                            try
                            {
                                final byte[] line = lines.get(i);
                                if (line.length == 0)
                                {
                                    continue;
                                }

                                // get us the minimal data aka type and time (reusing pooled instances for standard types)
                                final byte tcByte = line[0];
                                Data data;
                                if (tcByte == (byte) 'R' && poolRequests)
                                {
                                    final RequestData req = postProcessedData.getOrCreateRequestData(postProcessedData.size());
                                    req.setRawName(null);
                                    data = req;
                                }
                                else if (tcByte == (byte) 'A' && poolActions)
                                {
                                    if (nonRequestData == null)
                                    {
                                        nonRequestData = new PostProcessedDataContainer(64);
                                    }
                                    data = nonRequestData.getOrCreateActionData(actionPoolIdx++);
                                }
                                else if (tcByte == (byte) 'T' && poolTransactions)
                                {
                                    if (nonRequestData == null)
                                    {
                                        nonRequestData = new PostProcessedDataContainer(64);
                                    }
                                    data = nonRequestData.getOrCreateTransactionData(txnPoolIdx++);
                                }
                                else if (tcByte == (byte) 'C' && poolCustom)
                                {
                                    if (nonRequestData == null)
                                    {
                                        nonRequestData = new PostProcessedDataContainer(64);
                                    }
                                    data = nonRequestData.getOrCreateCustomData(customPoolIdx++);
                                }
                                else
                                {
                                    data = dataRecordFactory.createStatistics(tcByte);
                                }

                                // parse, the columns structure is reused
                                CsvByteLineDecoder.parse(csvColumns, line);
                                data.setBaseValues(csvColumns);

                                // see if we have to keep it
                                final long time = data.getTime();
                                if (time < _fromTime || time > _toTime)
                                {
                                    // nope
                                    continue;
                                }

                                // finish parsing
                                data.setRemainingValues(csvColumns);

                                // set general fields
                                data.setAgentName(agentName);
                                data.setTransactionName(testCaseName);

                                // let's see if this data requires post processing aka filtering/merging
                                data = applyDataAdjustments(data, userNumber, collectActionNames, chunk, adjustTimerName);

                                // if this is request, filter it aka apply merge rules
                                if (data instanceof RequestData)
                                {
                                    final RequestData reqData = (RequestData) data;
                                    // Snapshot the original unmerged timer name (e.g. "Homepage.1.2") BEFORE MergeRuleProcessor
                                    // mutates reqData.setName(...) in-place, so TelemetryStore's Cold Forensic Tail Block can preserve
                                    // both the post-merge group name and the pre-merge raw request name for forensic drill-down.
                                    if (reqData.getRawName() == null)
                                    {
                                        reqData.setRawName(reqData.getName());
                                    }
                                    final RequestData result = requestProcessing.postprocess(reqData);
                                    if (result != null)
                                    {
                                        postProcessedData.add(result);
                                    }
                                }
                                else
                                {
                                    // get us a hashcode for later while the cache is warm
                                    // for RequestData, we did that already
                                    final String name = data.getName();
                                    if (name != null)
                                    {
                                        name.hashCode();
                                    }
                                    if (nonRequestData == null)
                                    {
                                        nonRequestData = new PostProcessedDataContainer(64);
                                    }
                                    nonRequestData.add(data);
                                }
                            }
                            catch (final Exception ex)
                            {
                                final int lineNumber = baseLineNumber + i;
                                final String lineStr = new String(lines.get(i), java.nio.charset.StandardCharsets.UTF_8);
                                final String msg = String.format("Failed to parse data record at line %,d in file '%s': %s\nLine is: %s", lineNumber,
                                                                 file, ex, lineStr);
                                LOG.error(msg, ex);

                                continue;
                            }
                        }
                    }
                    finally
                    {
                        chunk.notifyActionNamesCollected();
                    }

                    final boolean hasNonReq = nonRequestData != null && nonRequestData.size() > 0;
                    final boolean hasReq = postProcessedData.size() > 0;

                    // Deliver non-request records if present (tagged with homogeneous typeCode if applicable)
                    if (hasNonReq)
                    {
                        final int nonReqCount = nonRequestData.size();
                        final char firstTc = nonRequestData.dataList.get(0).getTypeCode();
                        boolean homogeneous = true;
                        final Object[] internalArr = nonRequestData.dataList.getInternalArray();
                        for (int k = 1; k < nonReqCount; k++)
                        {
                            if (((Data) internalArr[k]).getTypeCode() != firstTc)
                            {
                                homogeneous = false;
                                break;
                            }
                        }
                        if (homogeneous)
                        {
                            nonRequestData.typeCode = firstTc;
                        }
                        final boolean isLast = !hasReq;
                        if (isLast)
                        {
                            finishedNotified = true;
                        }
                        dispatcher.addPostprocessedData(nonRequestData, isLast);
                    }

                    // Deliver request records if present (guaranteed 100% homogeneous 'R' chunk)
                    if (hasReq)
                    {
                        postProcessedData.typeCode = 'R';
                        finishedNotified = true;
                        dispatcher.addPostprocessedData(postProcessedData, true);
                    }
                    else if (!hasNonReq)
                    {
                        // Neither requests nor non-requests (e.g. all out of time range)
                        finishedNotified = true;
                        dispatcher.addPostprocessedData(postProcessedData, true);
                    }
                }
                catch (final InterruptedException e)
                {
                    Thread.currentThread().interrupt();
                    break;
                }
                catch (final Exception e)
                {
                    LOG.error(String.format("Failed to process data chunk from file '%s'", chunk.getFile()), e);
                }
                finally
                {
                    if (!finishedNotified)
                    {
                        dispatcher.finishedProcessing();
                    }
                }
            }
            catch (final InterruptedException e)
            {
                Thread.currentThread().interrupt();
                break;
            }
        }
    }

    private Data applyDataAdjustments(final Data data, 
                                      final String userNumber,
                                      final boolean collectActionNames, final DataChunk lineChunk, 
                                      final boolean adjustTimerName)
    {
        // Assign the virtual user instance number (e.g. "0", "1", ...) universally across all Data record types
        // (Transactions, Actions, Requests, Custom Timers, Custom Values, Web Vitals, Events). Storing this column
        // across all TelemetryStore chunk types enables cross-record correlation to reconstruct a single virtual user's
        // complete chronological breadcrumb trail.
        data.setTestUserNumber(userNumber);

        // set special fields / special handling
        if (collectActionNames && data instanceof ActionData)
        {
            // store the action name/time for later use
            lineChunk.getActionNames().put(data.getTime(), data.getName());
        }
        else if (adjustTimerName && (data instanceof RequestData || data instanceof PageLoadTimingData))
        {
            // rename web driver requests/custom timers using the previously stored action names
            final Entry<Long, String> entry = lineChunk.getActionNames().floorEntry(data.getTime());
            final String actionName = (entry != null) ? entry.getValue() : "UnknownAction";

            final Matcher m = WD_TIMER_NAME_PATTERN.matcher(data.getName());
            data.setName(m.replaceFirst(actionName));
        }

        return data;
    }
}
